#pragma once

#include <sc-memory/sc_agent.hpp>

// Реализует вычислимую часть правила rule_detect_anomalous_request_rate
// (ostis_kb_user_ecosystem/rules/rules_security_privacy.scs):
//   anomalous <- rate(source, target, dt) > k_sigma * baseline_rate(target)
//
// В отличие от EMA-агентов доверия, k_sigma не имеет в тексте правила
// характерного значения по умолчанию (у единого коэффициента сглаживания
// eta было явное "типично 0.10", у k_sigma -- нет никакого числа, только
// "27x" в иллюстративном сценарии, что описывает конкретное НАБЛЮДЕНИЕ,
// а не порог) -- поэтому k_sigma здесь обязательный аргумент действия.
// У EMA-агентов eta тоже передан аргументом действия, но необязательным:
// при его отсутствии используется значение по умолчанию 0.10.
//
// Аргументы sc-действия action_detect_anomalous_request_rate:
//   1) rate_link     -- числовая sc-ссылка с наблюдаемой частотой
//                        запросов rate(source, target, dt)
//   2) baseline_link -- числовая sc-ссылка с базовой линией
//                        baseline_rate(target)
//   3) k_sigma_link  -- числовая sc-ссылка с пороговым множителем k_sigma
//   4) result_level  -- узел для индикатора аномалии (1 -- аномалия
//                        обнаружена, 0 -- нет); если у него ещё нет
//                        числовой sc-ссылки, она создаётся
//
// Результат: значение индикатора в value_link (4-й аргумент) записывается
// на месте. Если аномалия обнаружена -- дополнительно генерируется
// экземпляр concept_security_incident, классифицированный также
// concept_incident_denial_of_service (AGENTS_AUDIT.md п.6.9: правило
// оставляет выбор между DoS и Tampering неформализованным, но сигнал
// этого агента -- чисто объёмный (rate/baseline), содержимого запросов
// он не видит, поэтому обосновать можно только DoS), и соединяется
// с result_level простой положительной постоянной дугой (структурная
// связь для трассируемости, не именованное отношение онтологии -- по
// аналогии с тем, как trust_level хранит свой value_link).
//
// Не реализованы (AGENTS_AUDIT.md п.6.9, остаток): связывание инцидента
// с субъектом/системой/запросом/периодом наблюдения, запись аудита,
// снижение t_sec, приостановка маршрута, запуск проверки доступа,
// переназначения или эскалации -- каждое требует либо новых отношений
// онтологии, для которых ни правило, ни аудит не называют конкретных
// идентификаторов (в отличие от, например, is_input_for в п.6.10), либо
// агентов, не реализованных в проекте (agent_coalition_reconfigurator,
// agent_provenance_registrar -- см. §7 аудита).
//
// baseline_link <= 0 обрабатывается отдельно (деление на 0
// не определено): если при этом rate_link > 0, это трактуется как
// аномалия (внезапный трафик у компонента без истории обращений);
// если rate_link тоже <= 0 -- как отсутствие аномалии.
class AgentDetectAnomalousRequestRate : public ScActionInitiatedAgent
{
public:
  ScAddr GetActionClass() const override;

  ScResult DoProgram(ScAction & action) override;
};
